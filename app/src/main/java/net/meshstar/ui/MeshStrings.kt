@Composable fun tr(key: T): String = LocalContext.current.getString(key.resource)

/** Preserve the Activity context chain for camera launchers while selecting resources. */
fun localizedContext(base: android.content.Context, language: String): android.content.Context {
    if (language.isEmpty()) return base
    val config = android.content.res.Configuration(base.resources.configuration).apply { setLocale(java.util.Locale.forLanguageTag(language)) }
    val localized = base.createConfigurationContext(config)
    return object : android.content.ContextWrapper(base) {
        override fun getResources(): android.content.res.Resources = localized.resources
        override fun getAssets(): android.content.res.AssetManager = localized.assets
    }
}
